// Builds the Romanian and English pages from index.html (the Russian source page).
//   npm run pages
// Writes:  ro/index.html, en/index.html — full static pages Google can index;
//          i18n.js — all three languages for instant switching on the site;
//          sitemap.xml — with links between the language versions.
// Fails with a list of keys if any text is missing a translation.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {parseHTML} from 'linkedom';
import {ro, en} from '../translations.mjs';

const SITE = 'https://ius-auto.github.io';
const PATH = {ru: '/', ro: '/ro/', en: '/en/'};
const LOCALE = {ru: 'ru_MD', ro: 'ro_MD', en: 'en_US'};
const file = f => fileURLToPath(new URL('../' + f, import.meta.url));

const source = await readFile(file('index.html'), 'utf8');
const SAFE = v => !/</.test(v.replace(/<\/?(br|em)>/g, ''));

// ---- Russian texts are read from the source page itself ----
const {document: src} = parseHTML(source);
const ru = {};
src.querySelectorAll('[data-i]').forEach(el => { if (!(el.dataset.i in ru)) ru[el.dataset.i] = el.innerHTML.trim(); });
src.querySelectorAll('[data-alt]').forEach(el => { ru[el.dataset.alt] = el.getAttribute('alt'); });
src.querySelectorAll('[data-aria]').forEach(el => { ru[el.dataset.aria] = el.getAttribute('aria-label'); });
const metaContent = (doc, sel) => doc.querySelector(sel)?.getAttribute('content') ?? '';
const schemaOf = doc => JSON.parse(doc.querySelector('script[type="application/ld+json"]').textContent);
Object.assign(ru, {
  metaTitle: src.title,
  metaDescription: metaContent(src, 'meta[name=description]'),
  ogTitle: metaContent(src, 'meta[property="og:title"]'),
  ogDescription: metaContent(src, 'meta[property="og:description"]'),
  schemaDescription: schemaOf(src).description,
});

// ---- Every key must exist in every language ----
const dict = {ru, ro, en};
const missing = [];
for (const lang of ['ro', 'en']) for (const k of Object.keys(ru)) if (!dict[lang][k]) missing.push(`${lang}.${k}`);
for (const lang of ['ro', 'en']) for (const [k, v] of Object.entries(dict[lang])) if (!SAFE(v)) missing.push(`${lang}.${k} (only <br>/<em> allowed)`);
if (missing.length) { console.error('Missing or unsafe translations:\n  ' + missing.join('\n  ')); process.exit(1); }

// ---- i18n.js: only the keys the page uses ----
const pick = d => Object.fromEntries(Object.keys(ru).map(k => [k, d[k]]));
await writeFile(file('i18n.js'),
  '// Generated by `npm run pages` from index.html and translations.mjs. Do not edit by hand.\n' +
  'window.IUS_I18N=' + JSON.stringify({ru, ro: pick(ro), en: pick(en)}) + ';\n');

// ---- ro/ and en/ pages ----
for (const lang of ['ro', 'en']) {
  const t = dict[lang];
  const {document: doc} = parseHTML(source);
  doc.documentElement.setAttribute('lang', lang);
  doc.querySelectorAll('[data-i]').forEach(el => { el.innerHTML = t[el.dataset.i]; });
  doc.querySelectorAll('[data-alt]').forEach(el => el.setAttribute('alt', t[el.dataset.alt]));
  doc.querySelectorAll('[data-aria]').forEach(el => el.setAttribute('aria-label', t[el.dataset.aria]));
  doc.querySelector('title').textContent = t.metaTitle;
  doc.querySelector('meta[name=description]').setAttribute('content', t.metaDescription);
  doc.querySelector('meta[property="og:title"]').setAttribute('content', t.ogTitle);
  doc.querySelector('meta[property="og:description"]').setAttribute('content', t.ogDescription);
  doc.querySelector('meta[property="og:locale"]').setAttribute('content', LOCALE[lang]);
  doc.querySelector('meta[property="og:url"]').setAttribute('content', SITE + PATH[lang]);
  doc.querySelector('link[rel=canonical]').setAttribute('href', SITE + PATH[lang]);
  const ld = doc.querySelector('script[type="application/ld+json"]');
  const schema = schemaOf(doc); schema.description = t.schemaDescription;
  ld.textContent = JSON.stringify(schema);
  doc.querySelectorAll('[data-lang]').forEach(a => a.setAttribute('aria-current', String(a.dataset.lang === lang)));
  await mkdir(file(lang), {recursive: true});
  await writeFile(file(`${lang}/index.html`), '<!doctype html>\n' + doc.documentElement.outerHTML + '\n');
  console.log(`${lang}/index.html`);
}

// ---- sitemap with language alternates ----
const today = new Date().toISOString().slice(0, 10);
const alts = Object.entries(PATH).map(([l, p]) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${SITE}${p}"/>`).join('\n');
await writeFile(file('sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${Object.values(PATH).map(p => `  <url>
    <loc>${SITE}${p}</loc>
    <lastmod>${today}</lastmod>
${alts}
    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}/"/>
  </url>`).join('\n')}
</urlset>
`);
console.log('i18n.js, sitemap.xml');
